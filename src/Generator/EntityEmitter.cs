using SourceLayout = Neemle.OrmLite.Generator.GeneratedSourceLayout.GeneratedSourceLayout;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using Microsoft.CodeAnalysis;
using Neemle.CSharpComposer;
using Neemle.CSharpComposer.Builders;
using Neemle.CSharpComposer.Model;
using Neemle.CSharpComposer.Rendering;
using ChildGuard = Neemle.OrmLite.Generator.OrmGenerator.ChildGuard;
using EmitScope = Neemle.OrmLite.Generator.OrmGenerator.EmitScope;
using Entity = Neemle.OrmLite.Generator.OrmGenerator.Entity;

namespace Neemle.OrmLite.Generator;

/// <summary>
/// Emits one generated file per bound declaration: reports what is wrong, then writes the static Orm class of each
/// entity, the purge class of each soft-delete entity, the schema class and the module initializer that registers the
/// descriptors.
/// </summary>
internal static class EntityEmitter
{
    internal const string GeneratedNamespace = "Neemle.OrmLite.Generated";

    internal const string Header = "// <auto-generated/>";

    internal const string EntitiesHint = "OrmLite.Entities.g.cs";

    private static readonly RenderOptions RenderOptions = new();

    internal static void EmitEntities(
        SourceProductionContext spc, ImmutableArray<Entity> all, string asmToken, ProviderSet providers)
    {
        EntityReports.Report(spc, all, providers);
        var blocked = NavigationAudit.Report(spc, all);
        var named = EntityNaming.Disambiguated(all);
        var dropped = new HashSet<string>(named.Where(OrmGenerator.Dropped).Select(e => e.Type));
        var emitted = named.Where(e => !OrmGenerator.Dropped(e));
        var source = EntitiesSource([.. emitted], asmToken, dropped, blocked);
        foreach (var (hint, text) in SourceLayout.Entities(source)) spc.AddSource(hint, text);
    }

    internal static FileBuilder NewFile() =>
        Cs.Document().Header(Header).Nullable(NullableMode.Enable).Namespace(GeneratedNamespace);

    internal static TypeBuilder<FileBuilder> Access(TypeBuilder<FileBuilder> type, string access) =>
        access == "public" ? type.Public() : type.Internal();

    private static string EntitiesSource(
        ImmutableArray<Entity> entities, string asmToken, HashSet<string> dropped,
        HashSet<(string Entity, string Nav)> blocked)
    {
        var allTables = new HashSet<string>(entities.Select(x => x.Table));
        var withheld = entities.Where(OrmGenerator.KeyedApiWithheld).Select(x => x.Type);
        var refused = new HashSet<string>(withheld.Concat(dropped));
        var scope = new EmitScope(allTables, refused, new ChildGuard(dropped, ExcludedPairs(entities), blocked));
        var file = NewFile();
        foreach (var e in entities)
        {
            file = EntityClassEmitter.EntityClass(file, e, scope);
            if (e.SoftDeleteColumn is not null) file = PurgeClass(file, e);
        }
        file = SchemaClass(file, entities, asmToken);
        file = InitializerClass(file, entities);
        return file.Render(RenderOptions);
    }

    private static HashSet<(string Type, string Member)> ExcludedPairs(ImmutableArray<Entity> entities)
    {
        var pairs = new HashSet<(string Type, string Member)>();
        foreach (var e in entities)
            if (!e.ExcludedMembers.IsDefaultOrEmpty)
                foreach (var name in e.ExcludedMembers)
                    pairs.Add((e.Type, name));
        return pairs;
    }

    private static FileBuilder PurgeClass(FileBuilder file, Entity e)
    {
        var entity = Cs.Type(e.Full);
        var func = Cs.Generic(Syn.SystemNamespace + "Func", entity, Cs.Bool);
        var predicate = Cs.Generic(Syn.SystemNamespace + "Linq.Expressions.Expression", func);
        var orm = Cs.Id(e.Type + "Orm");
        var guard = Cs.Statement(Cs.Id("System").Dot("ArgumentNullException").Dot("ThrowIfNull").Of(Cs.Id("where")));
        var direct = orm.Dot("Query").Of(Cs.Id("db"))
            .Dot("Where").Of(Cs.Id("where")).Dot("PurgeAsync").Of();
        var inside = orm.Dot("Query").Of(Cs.Id("db")).Dot("On").Of(Cs.Id("uow"))
            .Dot("Where").Of(Cs.Id("where")).Dot("PurgeAsync").Of();
        return Access(file.Class(e.Type + "Purge"), e.Access).Static()
            .Method(Syn.TaskOf(Cs.Int), "DeleteWhereAsync").Public().Static().Async()
                .Parameter(Syn.Context, "db").Parameter(predicate, "where").Body(guard, Syn.GiveAwaited(direct)).End()
            .Method(Syn.TaskOf(Cs.Int), "DeleteWhereAsync").Public().Static().Async()
                .Parameter(Syn.Context, "db").Parameter(Syn.Lite("UnitOfWork"), "uow").Parameter(predicate, "where")
                .Body(guard, Syn.GiveAwaited(inside)).End()
            .End();
    }

    private static FileBuilder SchemaClass(FileBuilder file, ImmutableArray<Entity> entities, string token) =>
        file.Class(token + "Schema").Public().Static()
            .Field(Syn.Lite("OrmSchema"), "Instance").Public().Static().ReadOnly()
                .Initialize(Syn.Static("OrmSchema", "Of").Of(
                    [Syn.Str(token), .. entities.Select(e => Cs.Id(e.Type + "Orm").Dot("Descriptor"))])).End()
            .End();

    private static FileBuilder InitializerClass(FileBuilder file, ImmutableArray<Entity> entities)
    {
        var registrations = entities
            .Select(e => Cs.Statement(Syn.Static("OrmMeta", "Register")
                .OfTypes(Cs.Type(e.Full))
                .Of(Cs.Id(e.Type + "Orm").Dot("Descriptor"))))
            .ToArray();
        return file.Class("OrmMetaInit").Internal().Static()
            .Method(Cs.Void, "Init").Internal().Static()
                .Attribute(Cs.Attribute(Syn.Sys("Runtime.CompilerServices.ModuleInitializer")))
                .Body(registrations).End()
            .End();
    }
}
