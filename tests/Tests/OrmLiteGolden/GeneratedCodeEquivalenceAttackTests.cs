using System;
using System.IO;
using System.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Xunit;

namespace Neemle.OrmLite.Tests.OrmLiteGolden;

public sealed class GeneratedCodeEquivalenceAttackTests
{
    private static readonly CSharpParseOptions Parse =
        new(LanguageVersion.Latest);

    private static SyntaxTree Parsed(string source, bool feature = false)
    {
        var options = feature
            ? Parse.WithPreprocessorSymbols("FEATURE")
            : Parse;

        var tree = CSharpSyntaxTree.ParseText(source, options);
        Assert.DoesNotContain(tree.GetDiagnostics(),
            d => d.Severity == DiagnosticSeverity.Error);
        return tree;
    }

    private static void MustDiffer(string expected, string actual)
    {
        Parsed(expected);
        Parsed(actual);
        Assert.NotEqual(expected, actual);
        Assert.NotNull(
            GeneratedCodeEquivalence.Difference(expected, actual));
    }

    private static void MustMatch(string expected, string actual)
    {
        Parsed(expected);
        Parsed(actual);
        Assert.NotEqual(expected, actual);
        Assert.Null(
            GeneratedCodeEquivalence.Difference(expected, actual));
    }

    [Fact]
    public void F1_Moving_nullable_enable_changes_the_context_of_A()
    {
        const string expected =
            "#nullable disable\n" +
            "class A { public string F; }\n" +
            "#nullable enable\n" +
            "class B { public string F; }\n";

        const string actual =
            "#nullable disable\n" +
            "#nullable enable\n" +
            "class A { public string F; }\n" +
            "class B { public string F; }\n";

        MustDiffer(expected, actual);
    }

    [Fact]
    public void F1_Moving_documentation_changes_its_owner()
    {
        const string expected =
            "/// <summary>Documented type.</summary>\n" +
            "class A {}\n" +
            "class B {}\n";

        const string actual =
            "class A {}\n" +
            "/// <summary>Documented type.</summary>\n" +
            "class B {}\n";

        MustDiffer(expected, actual);
    }

    [Fact]
    public void F2_Disabled_string_contents_are_not_formatting()
    {
        const string expected =
            "#if FEATURE\n" +
            "class C { const string S = \"a  b\"; }\n" +
            "#endif\n";

        const string actual =
            "#if FEATURE\n" +
            "class C { const string S = \"a b\"; }\n" +
            "#endif\n";

        Parsed(expected, feature: true);
        Parsed(actual, feature: true);
        MustDiffer(expected, actual);
    }

    [Fact]
    public void F2_Security_newline_can_comment_out_a_tenant_check()
    {
        const string expected =
            "#if FEATURE\n" +
            "class C\n" +
            "{\n" +
            "    public static bool Allowed(bool sameTenant)\n" +
            "    {\n" +
            "        // audit\n" +
            "        if (!sameTenant) return false;\n" +
            "        return true;\n" +
            "    }\n" +
            "}\n" +
            "#endif\n";

        var actual = expected.Replace(
            "// audit\n",
            "// audit ",
            StringComparison.Ordinal);

        // Both active branches parse. The mutant has swallowed the
        // entire rejecting statement into a single-line comment.
        var activeExpected = Parsed(expected, feature: true);
        var activeActual = Parsed(actual, feature: true);

        Assert.Single(activeExpected.GetRoot().DescendantNodes()
            .OfType<IfStatementSyntax>());
        Assert.Empty(activeActual.GetRoot().DescendantNodes()
            .OfType<IfStatementSyntax>());

        // The oracle parses without FEATURE and collapses disabled text.
        MustDiffer(expected, actual);
    }

    // Refused: F2_Explicitly_preserved_documentation_spaces_must_survive demanded that `a  b` against `a b` inside a
    // `<code xml:space="preserve">` of a documentation comment fail. That is a pure whitespace change inside a comment,
    // which the rule of GeneratedCodeEquivalence declares formatting: a comment is compared by its content with every
    // run of whitespace made one space. xml:space is an instruction to the consumers of the documentation XML, not to
    // the compiler; the code is the same, and honouring it would turn the code oracle into an XML documentation oracle.

    [Theory]
    [InlineData(
        "#if (true&&true)\nclass C {}\n#endif\n",
        "#if (true && true)\nclass C {}\n#endif\n")]
    [InlineData(
        "//<auto-generated/>\nclass C {}\n",
        "// <auto-generated/>\nclass C {}\n")]
    [InlineData(
        "/// <summary>Alpha beta.</summary>\nclass C {}\n",
        "/// <summary>Alpha\n/// beta.</summary>\nclass C {}\n")]
    public void F2_Trivia_formatting_only_changes_must_pass(
        string expected, string actual)
    {
        MustMatch(expected, actual);
    }

    [Theory]
    [InlineData(false)]
    [InlineData(true)]
    public void F3_Current_census_header_predicate_rejects_equivalent_code(
        bool useCrLf)
    {
        var path = Path.Combine(
            RuntimeSources.LibraryRoot(),
            "tests", "Tests", "OrmLiteGolden", "Expected",
            "OrmLite.Entities.0000.g.cs.golden");

        var expected = File.ReadAllText(path);
        const string name = "FixtureNoteOrm";
        const string header = "public static class " + name;

        Assert.Contains(header + "\n{", expected);

        var actual = useCrLf
            ? expected.Replace("\n", "\r\n", StringComparison.Ordinal)
            : expected.Replace(
                header + "\n{", header + " {",
                StringComparison.Ordinal);

        MustMatch(expected, actual);

        // The census now selects the class as a declaration in the syntax tree: the line-38 text predicate this
        // witness copied is gone, so the witness asks the selector the census uses. The assertion is unchanged.
        var found = SoftDelete.PurgeUpsert.SoftPurgeGeneratedSourceCensusTests.Declaration(
            CSharpSyntaxTree.ParseText(actual, Parse).GetRoot(), name);

        Assert.True(found is not null,
            "The current census selector rejects equivalent formatting.");
    }

    // Controls for the withdrawn L1 and additional literal forms.
    [Theory]
    [InlineData("\"alpha\"", "\"beta\"")]
    [InlineData("@\"alpha\"", "@\"beta\"")]
    [InlineData("\"\"\"alpha\"\"\"", "\"\"\"beta\"\"\"")]
    [InlineData("\"alpha\"u8", "\"beta\"u8")]
    [InlineData("\"\"\"alpha\"\"\"u8", "\"\"\"beta\"\"\"u8")]
    [InlineData(
        "\"\"\"\n alpha\n \"\"\"",
        "\"\"\"\n beta\n \"\"\"")]
    [InlineData(
        "\"\"\"\n alpha\n \"\"\"u8",
        "\"\"\"\n beta\n \"\"\"u8")]
    [InlineData("$\"a{x}\"", "$\"b{x}\"")]
    [InlineData("$@\"a{x}\"", "$@\"b{x}\"")]
    [InlineData("$\"{x:N2}\"", "$\"{x:N3}\"")]
    [InlineData("$\"\"\"a{x}\"\"\"", "$\"\"\"b{x}\"\"\"")]
    [InlineData("$$\"\"\"a{{x}}\"\"\"", "$$\"\"\"b{{x}}\"\"\"")]
    [InlineData(
        "$$\"\"\"\n a{{x}}\n \"\"\"",
        "$$\"\"\"\n b{{x}}\n \"\"\"")]
    [InlineData("10L", "10")]
    [InlineData("10U", "10")]
    [InlineData("1.0F", "1.0D")]
    [InlineData("'a'", "'b'")]
    [InlineData("x + 1", "x - 1")]
    [InlineData("true", "false")]
    public void Control_Changed_active_expression_must_fail(
        string expectedExpression, string actualExpression)
    {
        static string Source(string expression) =>
            "class C { void M(int x) { var value = " +
            expression + "; } }";

        MustDiffer(
            Source(expectedExpression),
            Source(actualExpression));
    }

    [Fact]
    public void Control_Changed_ordinary_identifier_must_fail()
    {
        MustDiffer(
            "class C { int Alpha; }",
            "class C { int Beta; }");
    }

    [Fact]
    public void Control_Ordinary_verbatim_identifiers_may_match()
    {
        MustMatch(
            "class @Z { int @value; }",
            "class Z { int value; }");
    }

    [Fact]
    public void Control_Ordinary_layout_may_match()
    {
        MustMatch(
            "class C { int M(int x) { return x + 1; } }",
            "class C\r\n{\r\n  int M ( int x )\r\n" +
            "  {\r\n    return x + 1 ;\r\n  }\r\n}\r\n");
    }

    [Theory]
    [InlineData("class C { int X = ; }")] // Missing expression.
    [InlineData("class C { int X; } )")]  // Unexpected/skipped token.
    public void Control_Active_syntax_errors_must_fail(string actual)
    {
        Assert.Contains(
            CSharpSyntaxTree.ParseText(actual, Parse).GetDiagnostics(),
            d => d.Severity == DiagnosticSeverity.Error);

        var difference = GeneratedCodeEquivalence.Difference(
            "class C { int X; }", actual);

        Assert.NotNull(difference);
        Assert.StartsWith(
            "the generated source does not parse as C#:",
            difference);
    }

    [Fact]
    public void Control_Disabled_numeric_change_must_fail()
    {
        MustDiffer(
            "#if FEATURE\nclass C { const int X = 1; }\n#endif\n",
            "#if FEATURE\nclass C { const int X = 2; }\n#endif\n");
    }

    // Unconfirmed probes, not counted findings. ValueText equality
    // alone is insufficient evidence that these spellings bind alike.
    // Refused: the `@dynamic` case. The compiler binds `@dynamic` as
    // `dynamic` (the pair compiles, and `x.Member()` binds dynamically),
    // so it is the same code; GeneratedCodeEquivalenceTests pins it as such.
    [Theory]
    [InlineData(
        "class C { object M() { var x = 1; return x; } }",
        "class C { object M() { @var x = 1; return x; } }")]
    [InlineData(
        "class @unmanaged {} class Box<T> where T : unmanaged {}",
        "class @unmanaged {} class Box<T> where T : @unmanaged {}")]
    public void Probe_Contextual_identifier_escape_must_not_hide_change(
        string expected, string actual)
    {
        MustDiffer(expected, actual);
    }
}
