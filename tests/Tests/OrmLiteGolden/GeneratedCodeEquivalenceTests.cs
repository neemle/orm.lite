using Xunit;

namespace Neemle.OrmLite.Tests.OrmLiteGolden;

// The goldens of generated C# (OrmLiteGolden and the corpus *.g.cs entries) are judged by GeneratedCodeEquivalence.
// These mutants pin what that judgement means on a real golden: formatting moves pass, a changed token or a changed
// directive or comment fails and is named.
public sealed class GeneratedCodeEquivalenceTests
{
    private const string Golden = "tests/Tests/OrmLiteGolden/Expected/OrmLite.Entities.0000.g.cs.golden";

    private static string Pinned() =>
        File.ReadAllText(Path.Combine(RuntimeSources.LibraryRoot(), Golden.Replace('/', Path.DirectorySeparatorChar)));

    [Fact(DisplayName = "a golden is the same code as itself")]
    public void A_golden_is_equivalent_to_itself()
    {
        var pinned = Pinned();

        Assert.Null(GeneratedCodeEquivalence.Difference(pinned, pinned));
    }

    [Fact(DisplayName = "re-indenting, dropping blank lines, joining wrapped lines and CRLF line ends are formatting and pass")]
    public void A_formatting_only_change_is_equivalent()
    {
        var pinned = Pinned();
        var reflowed = Reflow(pinned);

        Assert.NotEqual(pinned, reflowed);
        Assert.True(reflowed.Split('\n').Length < pinned.Split('\n').Length / 2, "the reflow should join most lines");
        Assert.Null(GeneratedCodeEquivalence.Difference(pinned, reflowed));
        Assert.Null(GeneratedCodeEquivalence.Difference(reflowed, pinned));
    }

    [Theory(DisplayName = "a changed identifier, operator, literal, keyword, directive or comment is a different code and fails")]
    [InlineData("identifier", "r.GetGuid(", "r.GetString(")]
    [InlineData("operator", "e.Id == key", "e.Id != key")]
    [InlineData("string literal", "\"revision\"", "\"revisions\"")]
    [InlineData("boolean literal", "true", "false")]
    [InlineData("keyword", "public static", "internal static")]
    [InlineData("directive", "#nullable enable", "#nullable disable")]
    [InlineData("comment", "// <auto-generated/>", "// generated")]
    public void A_semantic_change_is_not_equivalent(string kind, string from, string to)
    {
        var pinned = Pinned();
        var at = pinned.IndexOf(from, StringComparison.Ordinal);
        Assert.True(at >= 0, kind + ": the golden no longer holds `" + from + "`");
        var mutant = pinned[..at] + to + pinned[(at + from.Length)..];

        var difference = GeneratedCodeEquivalence.Difference(pinned, mutant);

        Assert.NotNull(difference);
        Assert.StartsWith("not the same code: golden line ", difference, StringComparison.Ordinal);
        // The same mutant also fails once the formatting around it has moved.
        Assert.NotNull(GeneratedCodeEquivalence.Difference(pinned, Reflow(mutant)));
    }

    [Fact(DisplayName = "a removed directive or comment fails although every token stays")]
    public void A_dropped_trivia_is_not_equivalent()
    {
        var pinned = Pinned();

        Assert.NotNull(GeneratedCodeEquivalence.Difference(pinned, pinned.Replace("#nullable enable\n", "", StringComparison.Ordinal)));
        Assert.NotNull(GeneratedCodeEquivalence.Difference(pinned, pinned.Replace("// <auto-generated/>\n", "", StringComparison.Ordinal)));
    }

    [Theory(DisplayName = "a verbatim @ is compared only on the words the compiler reads by spelling while binding")]
    // The @ only escapes a name: C# reads `@x` and `x` as the same identifier.
    [InlineData("class @Z { int @value; }", "class Z { int value; }", true)]
    [InlineData("class C { int f; int P { get => f; set => f = @value; } }", "class C { int f; int P { get => f; set => f = value; } }", true)]
    [InlineData("class C { void M(int @where) { _ = @where; } }", "class C { void M(int where) { _ = where; } }", true)]
    // The compiler binds `@dynamic` as `dynamic` (it reads that name by its value), so the @ changes nothing.
    [InlineData("class C { void M(@dynamic x) { x.Member(); } }", "class C { void M(dynamic x) { x.Member(); } }", true)]
    // Bare, these words are the implicit type, a native integer, a constraint, the nameof operator, a discard or the
    // backing field; with the @ they name a declared symbol.
    [InlineData("class C { void M() { @var x = 1; } }", "class C { void M() { var x = 1; } }", false)]
    [InlineData("class C { void M(@nint x) { } }", "class C { void M(nint x) { } }", false)]
    [InlineData("class C { void M(@nuint x) { } }", "class C { void M(nuint x) { } }", false)]
    [InlineData("class Box<T> where T : @unmanaged { }", "class Box<T> where T : unmanaged { }", false)]
    [InlineData("class Box<T> where T : @notnull { }", "class Box<T> where T : notnull { }", false)]
    [InlineData("class C { string M(int x) => @nameof(x); }", "class C { string M(int x) => nameof(x); }", false)]
    [InlineData("class C { void M(int x) { @_ = x; } }", "class C { void M(int x) { _ = x; } }", false)]
    [InlineData("class C { int P { get => @field; } }", "class C { int P { get => field; } }", false)]
    public void A_verbatim_identifier_counts_only_where_it_changes_the_meaning(string golden, string generated, bool same)
    {
        Assert.Equal(same, GeneratedCodeEquivalence.Difference(golden, generated) is null);
        Assert.Equal(same, GeneratedCodeEquivalence.Difference(generated, golden) is null);
    }

    [Fact(DisplayName = "a source that does not parse is never the same code")]
    public void An_unparsable_source_is_not_equivalent()
    {
        var pinned = Pinned();
        var broken = pinned[..pinned.LastIndexOf('}')];

        Assert.StartsWith("the generated source does not parse", GeneratedCodeEquivalence.Difference(pinned, broken), StringComparison.Ordinal);
        Assert.StartsWith("the golden source does not parse", GeneratedCodeEquivalence.Difference(broken, pinned), StringComparison.Ordinal);
    }

    [Fact(DisplayName = "the corpus judges its *.g.cs entries as code and every other entry as text")]
    public void The_corpus_compares_generated_sources_as_code()
    {
        Assert.True(Corpus.CorpusCatalog.IsGeneratedSource(new Corpus.CorpusEntry("generator-demo", "ormlite.entities.0000.g.cs", "")));
        Assert.False(Corpus.CorpusCatalog.IsGeneratedSource(new Corpus.CorpusEntry("generator-demo", "diagnostics", "")));
        Assert.False(Corpus.CorpusCatalog.IsGeneratedSource(new Corpus.CorpusEntry("query-read", "aggregate-avg", "")));
    }

    // A different layout of the same code: every line re-indented by two spaces, blank lines dropped, code lines joined
    // into one wherever no comment or directive stands between them, and CRLF line ends.
    private static string Reflow(string text)
    {
        var lines = new List<string>();
        var joinable = false;
        foreach (var raw in text.Replace("\r\n", "\n", StringComparison.Ordinal).Split('\n'))
        {
            var line = raw.Trim();
            if (line.Length == 0) continue;
            var code = !line.StartsWith('#') && !line.Contains("//", StringComparison.Ordinal);
            if (code && joinable) lines[^1] += " " + line;
            else lines.Add("  " + line);
            joinable = code;
        }
        return string.Join("\r\n", lines) + "\r\n";
    }
}
