using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Neemle.OrmLite.Tests;

// Judges two pieces of generated C# as the same code or not. Neemle.CSharpComposer renders through its own formatter
// and promises code equivalence, not the same bytes, so a golden of generated source is compared here rather than as
// text. Both sides are parsed with Roslyn and must be syntax-equivalent (SyntaxFactory.AreEquivalent, which compares
// every token's kind and text and ignores trivia), so a different identifier, operator, keyword or literal fails.
// Trivia that carries meaning is compared on top of that, in order: every directive (#nullable, #pragma, #if) and every
// comment, with whitespace inside it collapsed, so the `// <auto-generated/>` marker or `#nullable enable` cannot drop
// out unseen. Whitespace and line breaks between tokens are formatting and are ignored.
public static class GeneratedCodeEquivalence
{
    private static readonly CSharpParseOptions Parse = new(LanguageVersion.Latest);

    // Null when the two sources are the same code; otherwise where they first part, in the words of a test failure.
    public static string? Difference(string expected, string actual)
    {
        var left = CSharpSyntaxTree.ParseText(expected, Parse);
        var right = CSharpSyntaxTree.ParseText(actual, Parse);
        var unparsable = Errors(left, "golden") ?? Errors(right, "generated");
        if (unparsable is not null) return unparsable;
        if (SyntaxFactory.AreEquivalent(left, right, topLevel: false) && Trivia(left).SequenceEqual(Trivia(right), StringComparer.Ordinal))
            return null;
        return FirstDifference(Units(left), Units(right));
    }

    public static bool AreEquivalent(string expected, string actual) => Difference(expected, actual) is null;

    private static string? Errors(SyntaxTree tree, string side)
    {
        var error = tree.GetDiagnostics().FirstOrDefault(d => d.Severity == DiagnosticSeverity.Error);
        return error is null ? null : "the " + side + " source does not parse as C#: " + error;
    }

    private static IEnumerable<string> Trivia(SyntaxTree tree) => Units(tree).Where(u => u.Trivia).Select(u => u.Text);

    // The tree as a flat run of what is compared: tokens by text, meaningful trivia by collapsed text, each with the
    // line it starts on so a failure can point at it.
    private static List<Unit> Units(SyntaxTree tree)
    {
        var units = new List<Unit>();
        foreach (var token in tree.GetRoot().DescendantTokens(descendIntoTrivia: false))
        {
            foreach (var trivia in token.LeadingTrivia) AddTrivia(units, trivia);
            if (!token.IsKind(SyntaxKind.EndOfFileToken)) units.Add(new Unit(TextOf(token), Line(token.GetLocation()), false));
            foreach (var trivia in token.TrailingTrivia) AddTrivia(units, trivia);
        }
        return units;
    }

    // AreEquivalent reads an identifier by its value (`@Id` is `Id`) and every other token by its text; so does this.
    private static string TextOf(SyntaxToken token) => token.IsKind(SyntaxKind.IdentifierToken) ? token.ValueText : token.Text;

    private static void AddTrivia(List<Unit> units, SyntaxTrivia trivia)
    {
        if (trivia.IsKind(SyntaxKind.WhitespaceTrivia) || trivia.IsKind(SyntaxKind.EndOfLineTrivia)) return;
        units.Add(new Unit(Collapse(trivia.ToFullString()), Line(trivia.GetLocation()), true));
    }

    private static string Collapse(string text)
    {
        var builder = new StringBuilder(text.Length);
        var space = false;
        foreach (var c in text.Trim())
        {
            if (char.IsWhiteSpace(c)) { space = true; continue; }
            if (space) builder.Append(' ');
            builder.Append(c);
            space = false;
        }
        return builder.ToString();
    }

    private static int Line(Location location) => location.GetLineSpan().StartLinePosition.Line + 1;

    private static string FirstDifference(List<Unit> golden, List<Unit> generated)
    {
        for (var i = 0; i < Math.Max(golden.Count, generated.Count); i++)
        {
            var left = i < golden.Count ? golden[i] : null;
            var right = i < generated.Count ? generated[i] : null;
            if (left == right) continue;
            return "not the same code: golden " + Describe(left) + ", generated " + Describe(right);
        }
        return "not the same code, although the token runs match";
    }

    private static string Describe(Unit? unit) =>
        unit is null ? "<end of file>" : "line " + unit.Line + " `" + Clip(unit.Text) + "`";

    private static string Clip(string text) => text.Length <= 120 ? text : text[..120] + "...";

    private sealed record Unit(string Text, int Line, bool Trivia)
    {
        public bool Equals(Unit? other) => other is not null && other.Text == Text && other.Trivia == Trivia;

        public override int GetHashCode() => HashCode.Combine(Text, Trivia);
    }
}
